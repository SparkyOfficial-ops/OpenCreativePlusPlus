package com.opencreativeplus.api.plot

/**
 * Enum representing the three operational modes of a plot.
 */
enum class PlotMode {
    /**
     * Build mode: Creative building with flight and infinite blocks, scripts disabled
     */
    BUILD,
    
    /**
     * Dev mode: Visual coding interface with glass grid and coding blocks
     */
    DEV,
    
    /**
     * Play mode: Script execution enabled, interactive gameplay
     */
    PLAY
}
